"""Fetch AI-generated images made by OTHER generators from Wikimedia Commons (public-domain / CC0 outputs).

    SSL_CERT_FILE=<certifi> ml_env/bin/python -I build/fetch_ai_web.py <out_dir>

For each generator category: list files, keep JPEG/PNG with short side >= 700 px, download up to CAND at random, then keep
the PER most photograph-like (zero-shot CLIP: 'a photograph' vs 'an illustration / painting / digital art') so the test
is about photo detection, not artwork. Records generator, licence, source page. Writes <out_dir>/index.json.
"""
import json
import os
import random
import re
import sys
import time
import urllib.parse
import urllib.request

import numpy as np
import open_clip
import torch
from PIL import Image

OUT = sys.argv[1]
os.makedirs(OUT, exist_ok=True)
UA = {"User-Agent": "insurance_firmFraudWorkbenchPOC/1.0 (Databricks field-eng demo)"}
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ST = os.path.join(ROOT, "wb_data", "ml_models", "hf_clip", "open_clip_pytorch_model.safetensors")
CATS = {"DALL-E": "Images generated by DALL-E", "Midjourney": "Images generated by Midjourney",
        "Stable Diffusion": "Images generated by Stable Diffusion", "ChatGPT/GPT Image": "Images generated by ChatGPT",
        "Flux": "Images generated by Flux (text-to-image model)", "Grok": "Images generated by Grok",
        "Meta AI": "Images generated by Meta AI", "Adobe Firefly": "Images generated by Adobe Firefly AI",
        "Ideogram": "Images generated by Ideogram", "Imagen": "Images generated by Imagen",
        "Bing Image Creator": "Images generated by Image Creator by Microsoft Bing"}
CAND, PER = 40, 6
random.seed(5)


def get(url, binary=False):
    for a in range(6):
        try:
            d = urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60).read()
            return d if binary else json.loads(d)
        except Exception as e:
            if "429" in str(e):
                time.sleep(8 * (a + 1)); continue
            raise
    raise RuntimeError("rate limited")


def api(**p):
    p["format"] = "json"
    time.sleep(1)
    return get("https://commons.wikimedia.org/w/api.php?" + urllib.parse.urlencode(p))


def files_in(cat):
    out, c = [], None
    while len(out) < 400:
        q = dict(action="query", list="categorymembers", cmtitle="Category:" + cat, cmlimit=500, cmtype="file")
        if c:
            q["cmcontinue"] = c
        d = api(**q)
        out += [m["title"] for m in d["query"]["categorymembers"]]
        c = d.get("continue", {}).get("cmcontinue")
        if not c:
            break
    return out


def info(titles):
    res = []
    for i in range(0, len(titles), 40):
        d = api(action="query", titles="|".join(titles[i:i + 40]), prop="imageinfo", iiprop="url|mime|size|extmetadata")
        for p in d["query"]["pages"].values():
            ii = (p.get("imageinfo") or [{}])[0]
            if ii.get("mime") in ("image/jpeg", "image/png") and min(ii.get("width", 0), ii.get("height", 0)) >= 700 \
                    and ii.get("size", 0) < 9_000_000:
                m = ii.get("extmetadata", {})
                res.append(dict(title=p["title"], url=ii["url"], page=ii.get("descriptionurl"), mime=ii["mime"],
                                w=ii["width"], h=ii["height"], bytes=ii["size"],
                                licence=re.sub(r"<[^>]+>", "", m.get("LicenseShortName", {}).get("value", ""))[:60]))
    return res


model, _, pre = open_clip.create_model_and_transforms("ViT-L-14", pretrained=ST)
model.eval()
tok = open_clip.get_tokenizer("ViT-L-14")
PHOTO = ["a photograph taken with a camera", "a candid photo", "a realistic photo of real life"]
ART = ["an illustration", "a painting", "digital art", "a cartoon", "a render of a fantasy scene", "concept art"]
with torch.no_grad():
    T = model.encode_text(tok(PHOTO + ART), normalize=True)


def photo_score(path):
    with torch.no_grad():
        v = model.encode_image(pre(Image.open(path).convert("RGB")).unsqueeze(0), normalize=True)
        p = (100 * v @ T.T).softmax(-1)[0]
    return float(p[:len(PHOTO)].sum())


kept = []
for gen, cat in CATS.items():
    try:
        ts = files_in(cat)
        random.shuffle(ts)
        cands = info(ts[:CAND * 2])[:CAND]
    except Exception as e:
        print("category failed", gen, e); continue
    scored = []
    for c in cands:
        fn = f"web_{re.sub('[^a-z]', '', gen.lower())}_{len(scored)}.{'png' if c['mime'].endswith('png') else 'jpg'}"
        try:
            open(os.path.join(OUT, fn), "wb").write(get(c["url"], True))
            scored.append(dict(c, file=fn, generator=gen, photo_score=photo_score(os.path.join(OUT, fn))))
        except Exception as e:
            print("  skip", c["title"], str(e)[:60])
        time.sleep(0.4)
    scored.sort(key=lambda x: -x["photo_score"])
    for i, s in enumerate(scored):
        if i < PER:
            kept.append(s)
        else:
            os.remove(os.path.join(OUT, s["file"]))
    print(f"{gen}: {len(cands)} candidates, kept {min(PER, len(scored))}, "
          f"photo_score of kept {[round(s['photo_score'], 2) for s in scored[:PER]]}", flush=True)
json.dump(kept, open(os.path.join(OUT, "index.json"), "w"), indent=1)
print(len(kept), "web AI images kept")
